"""ask.py —— 带着旧记录回答问题（DESIGN.md §4.4）。

这个文件管三件事：
1. 按 §4.4 规定的顺序拼上下文（底色摘要 → 章节标题 → 三路召回 → 最近三天）
2. 调对话模型
3. **检查模型有没有说人话**：必须引用真实历史日期，不许出现禁止清单里的句式

第 3 件事是这个产品的底线。做不到就重试一次，再不行就照实标出来，
而不是把一句「你已经很棒了」递给用户。
"""

from __future__ import annotations

import re

from life import config, llm, retrieve, store

# §7.2 禁止清单，做成机器能查的表。每条 = (正则, 给用户看的说明)
禁止句式: list[tuple[str, str]] = [
    (r"你已经很棒了|你很棒了|你已经做得很好了", "空泛安慰：「你已经很棒了」"),
    (r"相信自己|要相信|你可以的", "空泛安慰：「相信自己」"),
    (r"一切都会好|都会好起来|会好起来的|都会过去的", "空泛安慰：「一切都会好的」"),
    (r"加油|坚持住|别放弃", "空泛安慰：「加油」"),
    (r"你值得被爱|你值得拥有|你值得更好", "空泛安慰：「你值得」"),
    (r"听起来你确实|你确实不太行|你可能真的不适合|你的确做不到", "附和自我贬低"),
    (r"你有[^，。；]{0,8}(症|障碍|倾向)", "心理诊断"),
    (r"你应该(分手|辞职|退学|放弃|离开)", "价值判断"),
]

上下文上限 = 15000  # §4.4：上下文总长 ≤15k token，超了就减召回条数


def 估算token(文本: str) -> int:
    """粗估 token 数：中文一个字约 1.5，英文数字四个字符约 1。

    不用真的分词器：我们只需要一个「别超太多」的护栏，不需要精确账单。
    """
    中文 = sum(1 for 字 in 文本 if "\u4e00" <= 字 <= "\u9fff")
    其它 = len(文本) - 中文
    return int(中文 * 1.5 + 其它 / 4) + 1


def 问(
    问题: str, *, 取几条: int = 6, 用向量: bool = True
) -> dict:
    """问一个问题，返回：

        {
          "回答": 模型说的话,
          "没做到": [哪几条硬要求没做到],   # 空列表 = 全做到了
          "召回": [召回的那几条记录],
          "诊断": 检索过程的信息,
          "上下文token": 估算的上下文大小,
          "token": 本次花掉的 token,
        }
    """
    召回结果, 诊断 = retrieve.召回(问题, 取几条=取几条, 用向量=用向量)
    最近 = retrieve.最近几天(3)

    上下文 = _组装上下文(召回结果, 最近)
    # 上下文太长就砍召回条数（§4.4 的硬要求）
    while 估算token(上下文) > 上下文上限 and len(召回结果) > 2:
        召回结果 = 召回结果[:-1]
        上下文 = _组装上下文(召回结果, 最近)

    系统提示 = config.prompt文件("ask.md").read_text(encoding="utf-8")
    用户内容 = 上下文 + "\n\n---\n\n他现在说：" + 问题

    回复 = llm.调用("dialogue", 系统提示, 用户内容)
    没做到 = 校验回答(回复.文本, 上下文)

    # 没做到就回喂一次，让它改（§4.4 的三条是硬要求）
    if 没做到:
        再试 = 用户内容 + (
            "\n\n你上一次的回答没满足要求：\n- "
            + "\n- ".join(没做到)
            + "\n请重写一遍，务必做到。"
        )
        第二次 = llm.调用("dialogue", 系统提示, 再试)
        没做到2 = 校验回答(第二次.文本, 上下文)
        if len(没做到2) <= len(没做到):
            回复, 没做到 = 第二次, 没做到2

    return {
        "回答": 回复.文本,
        "没做到": 没做到,
        "召回": 召回结果,
        "诊断": 诊断,
        "上下文token": 估算token(用户内容),
        "token": 回复.输入token + 回复.输出token,
    }


# ── 拼上下文（顺序照 §4.4 来）───────────────────────────────


def _组装上下文(召回结果: list[dict], 最近: list[dict]) -> str:
    段: list[str] = []

    段.append("## 他的底色（长期是什么样的人，最多 15 行）")
    段.append(_底色摘要())

    段.append("\n## 他正在做的事（只有章节标题）")
    段.append(_章节标题())

    段.append("\n## 和他现在这句话相关的过去记录（每条都带日期）")
    段.append(
        "\n".join(_一条(条目) for 条目 in 召回结果)
        if 召回结果
        else "（没有找到相关的旧记录。）"
    )

    段.append("\n## 最近三天的记录")
    三天 = [e for e in 最近 if e["id"] not in {x["id"] for x in 召回结果}]
    段.append("\n".join(_一条(条目) for 条目 in 三天) if 三天 else "（最近三天没写。）")

    return "\n".join(段)


def _一条(条目: dict) -> str:
    """一条记录在上下文里长什么样。日期必须在最前面——模型得靠它引用细节。

    用 `when`（人话时间：「大学期间」「大一」）优先，没有才退回时间戳。
    不然简历里的事会被当成「今天」——实测模型真的会说「你的记录里全是今天」。
    """
    日期 = (条目.get("when") or "").strip() or 条目["ts"][:10]
    档 = {0: "接触", 1: "复现", 2: "产出", 3: "能讲"}.get(条目["level"], "?")
    行 = [f"- {日期}（{档} 档，{条目['part']}）：{条目['did']}"]

    锚点 = list(条目["anchors"]["tech"]) + list(条目["anchors"]["people"])
    if 锚点:
        行.append(f"    锚点：{'、'.join(锚点)}")
    if 条目["blockers"]:
        行.append(f"    当时的卡点：{'；'.join(条目['blockers'])}")
    原话 = 条目["emotion"]["quote"]
    if 原话:
        行.append(f"    他的原话：「{原话}」")
    if 条目["emotion"]["valence"]:
        行.append(f"    当时的情绪：{条目['emotion']['valence']:+.1f}")
    return "\n".join(行)


def _底色摘要() -> str:
    """core.md 压成最多 15 行（§4.4）。现在这个文件还是空的，第 3 周才有内容。"""
    路径 = store.确保vault就绪() / "core.md"
    文本 = 路径.read_text(encoding="utf-8") if 路径.exists() else ""
    文本 = re.sub(r"<!--.*?-->", "", 文本, flags=re.S)  # 去掉注释
    行们 = [行.strip() for 行 in 文本.splitlines() if 行.strip()]
    行们 = [行 for 行 in 行们 if not 行.startswith("#")]
    if not 行们:
        return "（还没有底色。底色是第 3 周靠证据晋升上来的。）"
    return "\n".join(行们[:15])


def _章节标题() -> str:
    """只给标题，不给全文（§4.4 明确要求）。"""
    目录 = store.确保vault就绪() / "chapters"
    标题们 = []
    for 文件 in sorted(目录.glob("*.md")):
        标题 = 文件.stem
        for 行 in 文件.read_text(encoding="utf-8").splitlines()[:20]:
            if 行.startswith("title:"):
                标题 = 行.split(":", 1)[1].strip().strip('"')
                break
        标题们.append(f"- {标题}")
    if not 标题们:
        return "（还没有主题。主题是归纳出来、经你确认之后才有的。）"
    return "\n".join(标题们)


# ── 检查模型有没有说人话 ─────────────────────────────────────


def 校验回答(回答: str, 上下文: str) -> list[str]:
    """§4.4 的验收：查有没有真实历史日期、有没有踩禁止清单。返回没做到的地方。"""
    没做到: list[str] = []

    # ① 必须引用一个真实存在过的日期
    if not _提到了真实日期(回答, 上下文):
        没做到.append(
            "回答里没有出现任何一条记录的真实日期。必须挑一条旧记录，说出日期和具体内容。"
        )

    # ② 禁止清单
    for 模式, 说明 in 禁止句式:
        if re.search(模式, 回答):
            没做到.append(f"出现了禁止的句式——{说明}")

    # ③ 一次最多给一个建议
    if _建议条数(回答) >= 3:
        没做到.append("一次给了三条以上建议。只给一个，而且要小到他能拒绝。")

    return 没做到


def _提到了真实日期(回答: str, 上下文: str) -> bool:
    """回答里有没有引用上下文里出现过的「时间标记」。

    时间标记不一定是完整日期：补记的旧事可能只知道「大学期间」「2023」。
    所以这里从上下文的每条记录开头收集标记，再额外收集 4 位年份。
    """
    候选: set[str] = set()

    for 行 in 上下文.splitlines():
        行 = 行.strip()
        if not 行.startswith("- "):
            continue
        # 记录开头长这样：- 大学期间（产出一档，record）：…   /   - 2026-11-25（…）：…
        匹配 = re.match(r"-\s*([^\s（(]+)", 行)
        if 匹配:
            标记 = 匹配.group(1).strip("，。：: ")
            if len(标记) >= 2:
                候选.add(标记)

    # 完整日期再派生出「10-16」「10 月 16 日」这些常见写法
    for 日期 in re.findall(r"\d{4}-\d{2}-\d{2}", 上下文):
        年, 月, 日 = 日期.split("-")
        候选.update(
            {
                日期,
                f"{月}-{日}",
                f"{int(月)} 月 {int(日)} 日",
                f"{int(月)}月{int(日)}日",
                f"{int(月)} 月{int(日)} 日",
            }
        )

    # 年份也算（回答常说「2024 年」「2025 和 2026」）
    候选.update(re.findall(r"(?:19|20)\d{2}", 上下文))

    if not 候选:
        return False  # 上下文里本来就没有任何时间标记，这条要求无从谈起
    return any(写 in 回答 for 写 in 候选)


def _建议条数(回答: str) -> int:
    """数一数它列了几条。我们要求不分点，所以出现三条以上列表就是在列建议。"""
    行们 = [行 for 行 in 回答.splitlines() if 行.strip()]
    return sum(1 for 行 in 行们 if re.match(r"^\s*(?:\d+[.、)]|[-*·])\s*\S", 行))
