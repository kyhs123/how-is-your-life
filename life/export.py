"""export.py —— 把记录导出成「能直接交出去的东西」（简历 / 微博 / 自我介绍 / 周报 / 任意）。

和「问一句」的区别：那边要的是一个回答，这边要的是**一个能发出去的文件**。
所以这里多做三件事：

1. **先挑素材**：只挑拿得出手的（档位高的优先），再混上和你这次要去的地方相关的记录。
   简历不该出现「今天没睡好」。
2. **一份指导文档**：`prompts/export_<模板>.md` 写清了格式、该写什么、别写什么。
   这些文档不是随手写的——简历那份是对着网上的简历规范整理的（文档里有来源）。
3. **一份交付物**：写到 `vault/导出/`，给你一个路径，你自己再改。

安全性上有一条硬要求：**素材里没有的东西，一个数字都不许写**。
写完会机械地核一遍数字，可疑的列在文件开头让你自己确认（模型编经历是这类工具最容易出的事）。
"""

from __future__ import annotations

import re
from pathlib import Path

from life import config, index, llm, retrieve, store

# ── 内置模板 ─────────────────────────────────────────────────
#
# 关键词用来从你的一句话里认出模板（「我要应聘机器人相关的工作，帮我生成一份简历」→ 简历）。
# 认不出来的走「通用」：由模型自己决定写成什么样，那份指导文档只讲底线，不讲格式。

模板们: dict[str, dict] = {
    "简历": {
        "指导": "export_简历.md",
        "后缀": ".md",
        "关键词": ("简历", "resume", "应聘", "求职", "投递", "招聘", "校招", "实习申请"),
        # 简历必需的基础信息（学历、绩点、证书）常常是「接触」档——
        # 只按档位挑会漏掉，所以按这几个词再捞一遍。
        "必带": ("在读", "GPA", "绩点", "本科", "硕士", "博士", "学位", "专业", "四级", "六级", "证书"),
    },
    "微博": {
        "指导": "export_微博.md",
        "后缀": ".txt",
        "关键词": ("微博", "动态", "朋友圈", "社交", "短文案", "发一条", "发个"),
    },
    "自我介绍": {
        "指导": "export_自我介绍.md",
        "后缀": ".txt",
        "关键词": ("自我介绍", "介绍一下自己", "介绍我", "三分钟", "30 秒", "30秒", "面试介绍"),
    },
    "周报": {
        "指导": "export_周报.md",
        "后缀": ".md",
        "关键词": ("周报", "月报", "汇报", "总结这周", "这周做了什么", "给导师", "给领导"),
    },
    "通用": {
        "指导": "export_通用.md",
        "后缀": ".md",
        "关键词": (),
    },
}

导出目录名 = "导出"
素材上限 = 26          # 给模型的记录条数上限（再多会把要求和底色挤掉）
数字模式 = re.compile(r"\d+(?:\.\d+)?")
列表号模式 = re.compile(r"(?m)^\s*\d+[.)、]\s")  # markdown 的有序列表编号，不算「编的数字」


def 选模板(要求: str) -> str:
    """从你的一句话里认出用哪个模板。认不出就通用。

    只认「这个模板独有的说法」：「面试」这种几个模板都沾边的词不算
    （说「面试要用，帮我写个自我介绍」时，认成简历就闹笑话了）。
    """
    低 = 要求.lower()
    for 名, 模板 in 模板们.items():
        if 名 == "通用":
            continue
        if any(词.lower() in 低 for 词 in 模板["关键词"]):
            return 名
    return "通用"


# ── 挑素材 ───────────────────────────────────────────────────


def 挑素材(
    要求: str, *, 上限: int = 素材上限, 必带: tuple[str, ...] = ()
) -> tuple[list[dict], dict]:
    """这次要导出的记录。

    三路混：
    1. 按你的要求检索（相关性）
    2. 档位高的（拿得出手）——简历里最该出现的往往是半年前那个「独立做完」的项目，
       它和「应聘机器人相关的工作」这句话在字面上未必像
    3. 模板声明的「必带」关键词命中（比如学历、绩点在「接触」档里）
    """
    相关, 诊断 = retrieve.召回(要求, 取几条=上限 // 2, 用向量=False)

    连接 = index.连接索引()
    try:
        行们 = 连接.execute(
            "SELECT id FROM entries WHERE private = 0 AND level >= 2 "
            "ORDER BY level DESC, ts DESC LIMIT ?",
            (上限,),
        ).fetchall()
        硬的 = [e for e in (index.取条目(连接, 行["id"]) for 行 in 行们) if e]

        基础的: list[dict] = []
        if 必带:
            全部 = 连接.execute("SELECT id FROM entries WHERE private = 0").fetchall()
            for 行 in 全部:
                条目 = index.取条目(连接, 行["id"])
                if not 条目:
                    continue
                文字 = 条目["did"] + " " + " ".join(条目["anchors"]["tech"])
                if any(词 in 文字 for 词 in 必带):
                    基础的.append(条目)
    finally:
        连接.close()

    见过: set[str] = set()
    结果: list[dict] = []
    # 顺序就是优先级：相关的 → 基础的 → 档位高的（有上限，先到先得）
    for 条目 in [*相关, *基础的, *硬的]:
        if 条目["private"] or 条目["id"] in 见过:
            continue
        见过.add(条目["id"])
        结果.append(条目)
        if len(结果) >= 上限:
            break

    结果.sort(key=lambda e: (-e["level"], e["ts"]), reverse=False)
    return 结果, 诊断


def _一条(条目: dict) -> str:
    日期 = (条目.get("when") or "").strip() or 条目["ts"][:10]
    档 = {0: "接触", 1: "复现", 2: "产出", 3: "能讲"}.get(条目["level"], "?")
    行 = f"- {日期}（{档}）：{条目['did']}"
    锚点 = list(条目["anchors"]["tech"]) + list(条目["anchors"]["people"])
    if 锚点:
        行 += f"　用到：{'、'.join(锚点)}"
    if 条目["minutes"]:
        行 += f"　约 {条目['minutes']} 分钟"
    if 条目.get("blockers"):
        行 += f"　卡过：{'；'.join(条目['blockers'])}"
    return 行


def 组装素材(要求: str, 条目们: list[dict]) -> str:
    """给模型的原材料。顺序：底色 → 目标 → 主题 → 记录。"""
    段 = ["## 他的底色（长期是什么样的人）"]
    项们 = store.读底色项()
    段.append(
        "\n".join(f"- {项.get('name', '')}：{(项.get('lines') or [''])[0][:80]}" for 项 in 项们[:12])
        if 项们
        else "（还没攒出来。）"
    )

    目标们 = store.全部目标()
    if 目标们:
        段.append("\n## 他立过的目标")
        段.append("\n".join(f"- {g['title']}（{g.get('status', '')}）" for g in 目标们[:8]))

    主题们 = store.全部章节()
    if 主题们:
        段.append("\n## 他真正在忙的那些事（主题）")
        段.append(
            "\n".join(
                f"- {c['title']}：{c.get('entry_count', 0)} 条记录" for c in 主题们[:8]
            )
        )

    段.append(f"\n## 他的记录（{len(条目们)} 条，重要的排前面）")
    段.append("\n".join(_一条(条目) for 条目 in 条目们) if 条目们 else "（一条都没有。）")

    段.append("\n## 他这次的原始要求")
    段.append(要求.strip())
    return "\n".join(段)


# ── 导出 ─────────────────────────────────────────────────────


def 导出目录() -> Path:
    目录 = store.确保vault就绪() / 导出目录名
    目录.mkdir(parents=True, exist_ok=True)
    return 目录


def _文件名(模板: str) -> str:
    后缀 = 模板们[模板]["后缀"]
    return f"{store.现在().strftime('%Y%m%d-%H%M')}-{模板}{后缀}"


def 可疑数字(正文: str, 素材: str) -> list[str]:
    """正文里出现、但素材里没有的数字。

    这条是防「模型编经历」的最后一道闸：它很笨，但编出来的「3 个专利」「提升 40%」
    一定会被抓到。抓到了不改，只在文件开头提醒你自己核。
    """
    有 = set(数字模式.findall(素材))
    干净 = 列表号模式.sub("", 正文)
    return sorted({数 for 数 in 数字模式.findall(干净) if 数 not in 有})


def 生成(要求: str, *, 模板: str = "", 上限: int = 素材上限) -> dict:
    """导出一次。返回 {"模板", "路径", "正文", "可疑数字", "条数", "token"}。"""
    要求 = (要求 or "").strip()
    if not 要求:
        raise ValueError("你还没说要导出成什么。比如：帮我生成一份应聘机器人岗位的简历。")

    模板 = 模板 or 选模板(要求)
    if 模板 not in 模板们:
        raise ValueError(f"没有「{模板}」这个模板。可选：{'、'.join(模板们)}")

    条目们, 诊断 = 挑素材(要求, 上限=上限, 必带=模板们[模板].get("必带", ()))
    素材 = 组装素材(要求, 条目们)

    系统提示 = config.prompt文件(模板们[模板]["指导"]).read_text(encoding="utf-8")
    回复 = llm.调用("dialogue", 系统提示, f"{素材}\n\n---\n\n请按上面的规矩，导出他要的东西。")
    正文 = 回复.文本.strip()

    可疑 = 可疑数字(正文, 素材)
    路径 = 导出目录() / _文件名(模板)
    路径.write_text(_加抬头(正文, 模板, 可疑), encoding="utf-8")

    return {
        "模板": 模板,
        "路径": 路径,
        "正文": 正文,
        "可疑数字": 可疑,
        "条数": len(条目们),
        "token": 回复.输入token + 回复.输出token,
        "诊断": 诊断,
    }


def _加抬头(正文: str, 模板: str, 可疑: list[str]) -> str:
    """文件开头写清「这是什么、什么时候导的、哪里要你自己核」。

    抬头不是给人看的装饰：导出物一旦发出去就代表你本人，
    所以「哪几处数字素材里没有」必须写在最上面，不能埋。
    """
    行 = [
        f"<!-- 由 life export 生成：{store.时间文本(store.现在())}｜模板：{模板} -->",
        "",
    ]
    if 可疑:
        行.append(
            "> ⚠️ 这几处数字在你的记录里找不到，可能是编的，发出去前自己核一遍："
            + "、".join(可疑)
        )
        行.append("")
    行.append(正文)
    return "\n".join(行) + "\n"
